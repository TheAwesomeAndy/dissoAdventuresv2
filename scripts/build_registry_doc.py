#!/usr/bin/env python3
"""Generate docs/EXPERIMENT_REGISTRY.md from docs/experiment_registry.json.

The JSON file is the source of truth. Edit it, then run this script. A test
(tests/test_repo_hygiene.py) fails if the two are out of step.

    python scripts/build_registry_doc.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "docs" / "experiment_registry.json"
DST = REPO / "docs" / "EXPERIMENT_REGISTRY.md"


def _code_list(items: list[str]) -> str:
    return ", ".join(f"`{i}`" for i in items) if items else "none"


def render(reg: dict) -> str:
    exps = reg["experiments"]
    out = ["# Experiment registry", "",
           "Generated by `scripts/build_registry_doc.py` from `docs/experiment_registry.json`. "
           "Do not edit by hand.", "",
           "Each entry answers: what question, on what data, with which code, by what protocol, "
           "producing which record, checked by what, and with which known problems. Statements about v1 "
           "scripts come from reading the code during the 2026-11-21 audit (`docs/REPOSITORY_AUDIT.md`), "
           "not from file names.", "",
           "## Tiers", ""]
    for tier, text in reg["tiers"].items():
        out.append(f"- **{tier}**: {text}")
    out += ["", "## Index", "", "| ID | Title | Tier | Chapter | Committed record |", "|---|---|---|---|---|"]
    for e in exps:
        out.append(f"| [{e['id']}](#{e['id'].lower()}) | {e['title']} | {e['tier']} | {e['chapter']} | "
                   f"{'yes' if e['records'] else 'no'} |")
    out.append("")
    for e in exps:
        out += [f"## {e['id']}", "", f"**{e['title']}**", "",
                f"- **Tier:** {e['tier']}",
                f"- **Question:** {e['question']}",
                f"- **Data:** {'; '.join(e['data'])}",
                f"- **Code:** {_code_list(e['scripts'])}",
                "- **Run:**"]
        out += [f"  - `{c}`" for c in e["commands"]]
        out += [f"- **Records and outputs:** {_code_list(e['records'])}",
                f"- **Model and encoding:** {e['model']}",
                f"- **Validation protocol:** {e['protocol']}",
                f"- **Statistics:** {e['statistics']}",
                f"- **Seeds and determinism:** {e['seeds']}",
                f"- **Metrics:** {e['metrics']}",
                f"- **Checked by:** {_code_list(e['verified_by'])}",
                f"- **Dissertation:** {e['dissertation']}"]
        if e.get("caveats"):
            out.append("- **Known problems and limits:**")
            out += [f"  - {c}" for c in e["caveats"]]
        out.append("")
    return "\n".join(out)


def main() -> int:
    DST.write_text(render(json.loads(SRC.read_text())))
    print(f"wrote {DST.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
