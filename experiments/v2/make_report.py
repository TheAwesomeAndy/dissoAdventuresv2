#!/usr/bin/env python3
"""Render experiments/v2/V2_RESULTS.md from v2_results.json.

Every number in the tables is read from the execution record, so the report cannot
drift from it.

    python experiments/v2/make_report.py [v2_results.json] [V2_RESULTS.md]
"""
import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
G = (("three_condition", "Three conditions"), ("four_category", "Four categories"))


def ba(r):
    return f"{r['balanced_accuracy_percent']:.1f}% [{r['ci95_percent'][0]:.1f}, {r['ci95_percent'][1]:.1f}]"


def dd(r):
    return f"{r['difference_pp']:+.1f} pp [{r['ci95_pp'][0]:+.1f}, {r['ci95_pp'][1]:+.1f}]"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] + ["---:"] * (len(header) - 1)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(_HERE, "v2_results.json")
    dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(_HERE, "V2_RESULTS.md")
    R = json.load(open(src))
    gr = R["granularities"]
    names = [(k, label) for k, label in G if k in gr]
    hdr = [label for _, label in names]
    fm = R["fading_memory"]
    rho = fm["selected_rho"]
    L = []
    L.append("# ARSPI-Net v2 results\n")
    L.append("Generated by `experiments/v2/make_report.py` from `experiments/v2/v2_results.json`. "
             "Do not edit by hand. Interpretation is in `V2_UPGRADE.md` at the repository root.\n")
    L.append(f"Cohorts: " + "; ".join(
        f"{label.lower()} {gr[k]['n_participants']} participants, {gr[k]['n_observations']} observations"
        for k, label in names) + ".\n")
    L.append(f"Protocol: {R['protocol']['cv']}. Readout: {R['protocol']['readout']}. "
             f"Intervals: {R['protocol']['intervals']}. Values are balanced accuracy with 95% intervals.\n")

    L.append("## 1. Fading memory of the deployed reservoir\n")
    L.append(f"Measured on {fm['sample']['n_sequences']} single-electrode input sequences drawn without "
             f"reference to labels. The rule: ESP-converged fraction >= {fm['rule']['esp_converged_fraction_min']}, "
             f"autonomous rate <= {fm['rule']['autonomous_rate_max']}, median feature reliability >= "
             f"{fm['rule']['reliability_median_r_min']}. **Selected recurrent gain: rho = {rho}** "
             f"(the largest value on the grid that passes). v1 used rho = 0.9.\n")
    L.append(table(
        ["rho", "recurrent / input current", "ESP converged", "spike disagreement (initial state)",
         "spike disagreement (1% input change)", "autonomous rate", "reliability median r", "reliability 10th pct", "passes"],
        [[s["rho"], f"{s['recurrent_to_input_current_ratio']:.2f}", f"{100 * s['esp_converged_fraction']:.0f}%",
          f"{100 * s['esp_mean_disagreement']:.1f}%", f"{100 * s['perturbation_mean_disagreement']:.1f}%",
          f"{s['autonomous_rate_after_input_off']:.4f}", f"{s['reliability_median_r']:.3f}",
          f"{s['reliability_p10_r']:.3f}", "yes" if s["passes"] else "no"] for s in fm["sweep_seed42"]]))
    L.append("\nAcross reservoir weight draws:\n")
    L.append(table(["rho", "draws passing", "ESP converged (range)", "reliability median r (range)", "autonomous rate (range)"],
                   [[k, f"{v['n_passing']} of {v['n_seeds']}",
                     f"{100 * v['esp_converged_fraction_range'][0]:.0f}% to {100 * v['esp_converged_fraction_range'][1]:.0f}%",
                     f"{v['reliability_median_r_range'][0]:.3f} to {v['reliability_median_r_range'][1]:.3f}",
                     f"{v['autonomous_rate_range'][0]:.4f} to {v['autonomous_rate_range'][1]:.4f}"]
                    for k, v in fm["across_reservoir_seeds"].items()]))

    L.append("\n## 2. v1 configuration recomputed by the v2 code\n")
    L.append(table(["Fit"] + hdr, [
        ["v1 estimator (direct fit)"] + [ba(gr[k]["v1_reproduction"]["v1_estimator_direct_fit"]) for k, _ in names],
        ["v2 estimator (row-space fit)"] + [ba(gr[k]["v1_reproduction"]["v2_estimator_row_space_fit"]) for k, _ in names],
        ["Prediction agreement"] + [f"{100 * gr[k]['v1_reproduction']['prediction_agreement_between_fits']:.2f}%" for k, _ in names]]))

    L.append("\n## 3. Held-out accuracy across the recurrent gain (one shared reservoir)\n")
    L.append(table(["rho"] + hdr, [[r] + [ba(gr[k]["rho_sweep_shared_reservoir"][r]) for k, _ in names]
                                   for r in gr[names[0][0]]["rho_sweep_shared_reservoir"]]))

    L.append("\n## 4. Representations and matched controls\n")
    lab = {
        "v2_headline_bsc6_srp64": f"**v2 headline: BSC6 / SRP-64, shared reservoir, rho = {rho}**",
        "raw_erp16": "Raw ERP, 16 bins",
        "amplitude6_matched_bins": "Amplitude, 6 bins (the BSC6 bin edges, no reservoir)",
        "nonspiking_bank_srp64": "Non-spiking leaky bank / SRP-64 (same input weights and leak)",
        "bsc6_srp64_no_recurrence": "BSC6 / SRP-64, recurrence off (rho = 0)",
        "bsc6_srp64_v1_gain_shared": "BSC6 / SRP-64, v1 gain (rho = 0.9), shared reservoir",
        "bsc6_srp64_v1_gain_per_electrode": "BSC6 / SRP-64, v1 configuration (rho = 0.9, per-electrode reservoirs)",
        "conventional": "Conventional band power and Hjorth",
    }
    fc = gr[names[0][0]]["feature_counts"]
    L.append(table(["Representation", "Features"] + hdr, [
        [lab[key], fc.get(key, 34 * 64)] + [ba(gr[k]["representations"][key]) for k, _ in names] for key in lab]))
    clab = {
        "headline_minus_amplitude6": "Headline minus 6-bin amplitude",
        "headline_minus_nonspiking_bank": "Headline minus non-spiking bank",
        "headline_minus_no_recurrence": "Headline minus recurrence off",
        "headline_minus_v1_gain_shared": "Headline minus v1 gain, shared",
        "headline_minus_v1_configuration": "Headline minus v1 configuration",
        "headline_minus_conventional": "Headline minus conventional",
        "raw_erp16_minus_headline": "Raw ERP-16 minus headline",
        "v1_gain_recurrence_effect_shared": "Effect of v1 recurrence (rho 0.9 minus rho 0, shared)",
        "v1_gain_per_electrode_minus_shared": "Per-electrode minus shared reservoir at rho 0.9",
    }
    L.append("\nPaired participant-bootstrap contrasts:\n")
    L.append(table(["Contrast"] + hdr, [[clab[c]] + [dd(gr[k]["contrasts"][c]) for k, _ in names] for c in clab]))

    L.append("\n## 5. Weight draws\n")
    rows = []
    for key in gr[names[0][0]]["seeds"]:
        s0 = gr[names[0][0]]["seeds"][key]
        rows.append([key.replace("_", " ") + f" (n = {len(s0['seeds'])})"] + [
            f"{gr[k]['seeds'][key]['mean']:.1f}% (sd {gr[k]['seeds'][key]['sd']:.2f}, "
            f"{gr[k]['seeds'][key]['min']:.1f} to {gr[k]['seeds'][key]['max']:.1f})" for k, _ in names])
    L.append(table(["Draws"] + hdr, rows))

    L.append("\n## 6. Windows in true milliseconds after stimulus onset\n")
    rows = []
    for w in gr[names[0][0]]["windows_ms"]:
        rows.append([w] + [f"{gr[k]['windows_ms'][w]['v2_headline_bsc6_srp64']:.1f}% / "
                           f"{gr[k]['windows_ms'][w]['amplitude6_matched_bins']:.1f}%" for k, _ in names])
    L.append(table(["Window (headline / 6-bin amplitude)"] + hdr, rows))

    L.append("\n## 7. Destruction controls on the headline code\n")
    L.append("Change in balanced accuracy against the intact headline. `train and test` refits on destroyed "
             "features (the v1 design). `test only` scores the intact-trained model on destroyed held-out rows.\n")
    rows = []
    for c in gr[names[0][0]]["destruction_controls"]:
        for mode in ("train_and_test", "test_only"):
            rows.append([f"{c.replace('_', ' ')}, {mode.replace('_', ' ')}"]
                        + [dd(gr[k]["destruction_controls"][c][mode]) for k, _ in names])
    L.append(table(["Control"] + hdr, rows))

    L.append("\n## 8. Compressors on the headline code\n")
    plab = {"srp64": "SRP-64 (fixed, data-independent)", "pca64_fold_local": "PCA-64, fitted on training participants",
            "pca64_fold_local_subject_centered_basis": "PCA-64, basis fitted after removing training-participant means",
            "none_full_1536_per_electrode": "No compression (1536 per electrode)"}
    L.append(table(["Compressor"] + hdr, [[plab[c]] + [ba(gr[k]["compressors"][c]) for k, _ in names] for c in plab]))
    L.append("")
    L.append(table(["Contrast"] + hdr, [[c.replace("_", " ")] + [dd(gr[k]["compressor_contrasts"][c]) for k, _ in names]
                                        for c in gr[names[0][0]]["compressor_contrasts"]]))

    L.append("\n## 9. Calibrated variance components\n")
    L.append("Fractions of total feature variance from the two-way subject x condition layout, with the mean "
             "of the permutation null in parentheses. The last column is the uncalibrated v1-style ratio of "
             "between-subject to between-condition variance, shown only to make its noise floor visible.\n")
    for k, label in names:
        L.append(f"**{label}**\n")
        L.append(table(["Representation", "Subject (null)", "Condition (null)", "Residual", "p subject", "p condition", "v1-style ratio"], [
            [key.replace("_", " "), f"{100 * v['fraction_subject']:.1f}% ({100 * v['subject_null_mean']:.1f}%)",
             f"{100 * v['fraction_condition']:.2f}% ({100 * v['condition_null_mean']:.2f}%)",
             f"{100 * v['fraction_residual']:.1f}%", f"{v['subject_p_value']:.4f}", f"{v['condition_p_value']:.4f}",
             f"{v['uncalibrated_v1_style_ratio']:.1f}"] for key, v in gr[k]["variance_components"].items()]))
        L.append("")

    if all("permutation" in gr[k] for k, _ in names):
        L.append("## 10. Within-participant permutation test, headline estimator\n")
        P = {k: gr[k]["permutation"]["v2_headline_bsc6_srp64"] for k, _ in names}
        L.append(table(["Quantity"] + hdr, [
            ["Observed (one repeat)"] + [f"{100 * P[k]['observed_balanced_accuracy']:.1f}%" for k, _ in names],
            ["Null mean (sd)"] + [f"{100 * P[k]['null_mean']:.1f}% ({100 * P[k]['null_sd']:.2f})" for k, _ in names],
            ["Null maximum"] + [f"{100 * P[k]['null_max']:.1f}%" for k, _ in names],
            ["Permutations"] + [P[k]["n_permutations"] for k, _ in names],
            ["Exceedances"] + [P[k]["n_exceedances"] for k, _ in names],
            ["p-value (floor)"] + [f"{P[k]['p_value']:.4f} ({P[k]['p_value_floor']:.4f})" for k, _ in names],
            ["Observed, in null SDs above the null mean"] + [f"{P[k]['observed_z_vs_null']:.1f}" for k, _ in names]]))
        L.append("")

    pv = R["provenance"]
    L.append("## Provenance\n")
    L.append(f"Generated {pv['generated_utc']} at commit `{pv['git_commit'][:12]}` with Python {pv['python']}, "
             f"NumPy {pv['numpy']}, SciPy {pv['scipy']}, scikit-learn {pv['scikit_learn']}. "
             f"Input files: {pv['input_file_counts']['data3']} three-condition, {pv['input_file_counts']['data4']} "
             f"four-category. Code hashes are in the execution record.\n")
    open(dst, "w").write("\n".join(L))
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
